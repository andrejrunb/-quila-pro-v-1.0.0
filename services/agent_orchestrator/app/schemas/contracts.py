"""
Áquila Pro — Orchestrator Contracts
Formal Pydantic v2 data models for pedagogical circuit specs, artifact manifests,
provenance, approvals, and idempotent publication receipts.
"""
from __future__ import annotations
import hashlib
import json
from typing import Literal, Dict, List
from pydantic import BaseModel, Field

# ---------------------------------------------------------------------------
# 1. Structured Pedagogical Specs & Provenance
# ---------------------------------------------------------------------------

class SourceProvenance(BaseModel):
    """Verifiable source registry and permitted licensing operations."""
    source_register_id: str = Field(description="Unique registry ID or exam code (e.g. INEP-ENEM-2023-FIS-01)")
    source_name: str = Field(description="Name of source, e.g. Exame Nacional do Ensino Médio")
    license_type: str = Field(description="License, e.g. Public Domain / CC BY-NC 4.0 / Institutional Authorization")
    allowed_operations: List[Literal["link", "embed", "offline_distribution", "adaptation"]] = Field(
        description="Explicit operations legally authorized for this item"
    )

class CircuitComponent(BaseModel):
    id: str = Field(description="Component identifier, e.g. R1, V1")
    type: Literal["resistor", "voltage_source", "switch", "voltmeter", "ammeter"]
    value: float = Field(description="Nominal numeric value")
    unit: Literal["Ohm", "kOhm", "V", "A", "mA"]
    tolerance_percent: float = Field(default=0.0, description="Tolerance for validation")

class CircuitConnection(BaseModel):
    node_a: str = Field(description="Starting node identifier, e.g. N0")
    node_b: str = Field(description="Ending node identifier, e.g. N1")
    component_id: str = Field(description="Connected component ID")

class StructuredCircuitSpec(BaseModel):
    """
    Structured, unit-checked representation of a resistive circuit.
    Enforces deterministic mathematical validation of Ohm and Kirchhoff laws.
    """
    topology: Literal["series", "parallel", "series_parallel"]
    components: List[CircuitComponent]
    connections: List[CircuitConnection]
    hypotheses: List[str] = Field(default_factory=list, description="Assumptions (e.g. fios ideais, gerador sem resistencia interna)")
    asked_quantity: str = Field(description="Quantity requested (e.g. corrente_total, tensao_em_r1)")
    expected_result: float = Field(description="Deterministically calculated target result")
    expected_unit: str = Field(description="Unit of expected result (e.g. A, V)")
    alternatives: Dict[str, float] = Field(description="Distractor and correct options e.g. {'A': 2.0, 'B': 5.0}")
    correct_alternative: str = Field(description="Letter corresponding to the correct answer, e.g. 'A'")

class PedagogicalTask(BaseModel):
    task_id: str
    school_id: str
    author_id: str
    subject: str = "Fisica"
    bncc_code: str = "EM13CNT308"
    provenance: SourceProvenance
    circuit_spec: StructuredCircuitSpec
    workflow_version: str = "2.1.0"

# ---------------------------------------------------------------------------
# 2. Artifacts & Claim-Check Manifest
# ---------------------------------------------------------------------------

class ArtifactItem(BaseModel):
    artifact_id: str
    artifact_type: Literal["statement_text", "answer_key", "circuit_schema", "audio_narration"]
    sha256_hash: str
    storage_path: str
    byte_size: int
    is_student_facing: bool
    contains_answer_key: bool

class ArtifactManifest(BaseModel):
    """Manifest describing all generated artifacts for a run."""
    run_id: str
    school_id: str
    artifacts: List[ArtifactItem]
    
    @property
    def manifest_hash(self) -> str:
        """Deterministic SHA-256 of all sorted artifact hashes in this package."""
        sorted_hashes = sorted([f"{a.artifact_id}:{a.sha256_hash}" for a in self.artifacts])
        raw = "|".join(sorted_hashes).encode("utf-8")
        return hashlib.sha256(raw).hexdigest()

# ---------------------------------------------------------------------------
# 3. Corrected Human Approval (HITL) Contract
# ---------------------------------------------------------------------------

class ApprovalRequestContract(BaseModel):
    """
    Server-issued approval contract.
    Decisions are recorded on backend; token changes invalidate approval.
    """
    approval_id: str = Field(description="Random UUID generated by server")
    run_id: str
    school_id: str
    artifact_manifest_hash: str = Field(description="SHA-256 of the exact artifact package being approved")
    workflow_version: str
    requested_action: str = Field(description="Action requested, e.g. publish_pedagogical_activity")
    requested_at: str
    expires_at: str
    reviewer_id: str | None = None
    decision: Literal["PENDING", "APPROVED", "REJECTED"] = "PENDING"
    rejection_reason: str | None = None
    decided_at: str | None = None
    consumed_at: str | None = None

# ---------------------------------------------------------------------------
# 4. Idempotent Publication Receipt
# ---------------------------------------------------------------------------

class PublicationReceipt(BaseModel):
    publication_id: str
    idempotency_key: str
    run_id: str
    school_id: str
    manifest_hash: str
    published_at: str
    server_signature_receipt: str
    status: Literal["SUCCESS", "ALREADY_PUBLISHED", "FAILED"]
