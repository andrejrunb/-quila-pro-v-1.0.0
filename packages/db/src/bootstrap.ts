export async function ensureSchema(execute: SqlExecutor): Promise<void> {
  for (const stmt of CREATE_STATEMENTS) {
    await execute(stmt, [], 'run');
  }

  for (const mod of ADDITIVE_COLUMNS) {
    const info = await execute(`PRAGMA table_info(${mod.table})`, [], 'all');
    const colNames = new Set(
      info.rows
        .map((r) => (Array.isArray(r) ? r[1] : undefined))
        .filter((v): v is string => typeof v === 'string')
    );
    if (colNames.size > 0 && !colNames.has(mod.column)) {
      await execute(mod.ddl, [], 'run');
    }
  }
}
